def emit_lower(path):
    lines = ["/* 5x7 mazosios raides su nuleidimais (bitas 0x10 = kaire; 9 eilutes: 7 kaip didziosiu + 2 po eilute)",
             " * - sugeneruota fontgen.py, rankomis nekeisti */",
             '#include "font.h"', "", "const uint8_t g_font5x7l[26][9] = {"]
    for ch in "abcdefghijklmnopqrstuvwxyz":
        rows = L5X7[ch]
        assert len(rows) == 9 and all(len(r) == 5 for r in rows), ch
        vals = [sum(1 << (4 - i) for i, c in enumerate(r) if c == "X") for r in rows]
        lines.append("    {" + ", ".join(f"0x{v:02X}" for v in vals) + "}, /* " + ch + " */")
    lines.append("};")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def emit(path, name, font, w, h, title):
    names = {" ": "space", '"': "dquote", "'": "apostrophe", "\\": "backslash", DEG: "degree"}
    lines = [f"/* {title} - sugeneruota fontgen.py, rankomis nekeisti */",
             '#include "font.h"', "", f"const uint8_t {name}[65][{h}] = {{"]
    for ch in [chr(c) for c in range(32, 96)] + [DEG]:
        rows = font[ch]
        assert len(rows) == h and all(len(r) == w for r in rows), ch
        vals = [sum(1 << (w - 1 - i) for i, c in enumerate(r) if c == "X") for r in rows]
        lines.append("    {" + ", ".join(f"0x{v:02X}" for v in vals) + "}, /* " + names.get(ch, ch) + " */")
    lines.append("};")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


